def sorted_files(entries: list[dict]) -> list[dict]:
    return sorted(entries, key=lambda entry: entry["path"])


def golden_document(
    image_name: str, image: bytes, files: list[dict], hashes: dict[str, str]
) -> dict:
    return {
        "image": image_name,
        "image_sha256": hashlib.sha256(image).hexdigest(),
        "volume_bytes": len(image),
        "files": sorted_files(files),
        "hashes": dict(sorted(hashes.items())),
    }


def write_gzip(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9) as gz:
            gz.write(data)


def write_json(path: Path, document: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False)
    path.write_text(text + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    repo = Path(__file__).resolve().parents[2]
    parser.add_argument("--images", type=Path, default=repo / "tests/fixtures/images")
    parser.add_argument("--golden", type=Path, default=repo / "tests/fixtures/golden")
    args = parser.parse_args()

    builders = {
        "ntfs_basic": build_basic,
        "ntfs_fragmented_mft": build_fragmented_mft,
        "ntfs_compressed": build_compressed,
        "ntfs_4k_sector": build_4k_sector,
        "ntfs_recyclebin": build_recyclebin,
    }

    for name, builder in builders.items():
        image, files, hashes = builder()
        image_name = name + ".img"
        write_gzip(args.images / (image_name + ".gz"), image)
        write_json(
            args.golden / (name + ".golden.json"),
            golden_document(image_name, image, files, hashes),
        )
        print(f"{image_name}: {len(image)} bytes, {len(files)} recoverable files")

    print(f"wrote {len(builders)} NTFS images to {args.images}")
    print(f"wrote {len(builders)} NTFS goldens to {args.golden}")
    return 0


