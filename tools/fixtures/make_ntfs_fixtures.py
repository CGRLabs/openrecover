def recycle_info_v1(path: str, size: int, deleted: int) -> bytes:
    """The Vista to 8 record: a 260-character path field padded with end-of-string characters."""
    encoded = utf16(path)
    assert len(encoded) <= 518, "the recorded path does not fit the fixed field"
    record = bytearray(24 + 520)
    put64(record, 0, 1)
    put64(record, 8, size)
    put64(record, 16, filetime(deleted) if deleted else 0)
    record[24 : 24 + len(encoded)] = encoded
    return bytes(record)


def recycle_info_v2(path: str, size: int, deleted: int) -> bytes:
    """The Windows 10 record: a character count, then exactly that many characters."""
    encoded = utf16(path) + b"\x00\x00"
    record = bytearray(28 + len(encoded))
    put64(record, 0, 2)
    put64(record, 8, size)
    put64(record, 16, filetime(deleted) if deleted else 0)
    put32(record, 24, len(encoded) // 2)
    record[28 :] = encoded
    return bytes(record)


def recycle_info_unreadable(path: str, size: int, deleted: int) -> bytes:
    """A record whose declared path length outruns the bytes it holds, as a metadata file that
    was partly overwritten by the next deletion looks."""
    record = bytearray(recycle_info_v2(path, size, deleted))
    declared = (len(record) - 28) // 2
    put32(record, 24, declared + 8)
    return bytes(record[:-16])


