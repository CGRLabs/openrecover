def unit_of(pattern: bytes, size: int) -> bytes:
    return (pattern * (size // len(pattern) + 1))[:size]


def mixed_compressed_bytes() -> bytes:
    """A compressed file with every shape a compression unit takes.

    One unit that shrank, one stored verbatim because noise does not compress, one that is a hole
    because it is all zeros, one that half-shrank, and a tail that stops inside a unit. The fuzz
    seeds reuse it, so the shapes the fixture writes and the shapes the fuzzer mutates match.
    """
    return b"".join(
        [
            unit_of(b"ntfs lznt1 compression unit zero\r\n", UNIT_BYTES),
            content_for("compressed/raw-unit.bin", UNIT_BYTES),
            bytes(UNIT_BYTES),
            content_for("compressed/noise-half.bin", UNIT_BYTES // 2) + b"\xAA" * (UNIT_BYTES // 2),
            unit_of(b"tail unit of a compressed file\r\n", 1200),
        ]
    )


def compressed_runs(
    units: list[tuple[str, bytes]], first_lcn: int
) -> tuple[list[tuple[int, int | None]], list[tuple[int, bytes]], int]:
    """Place the stored units on the volume and build the runlist Windows writes for them.

    A compressed attribute counts VCNs in the uncompressed space, so every unit is followed by a
    hole for the clusters its compressed form did not need, and adjacent holes merge into one run.
    Returns the runlist, the (lcn, bytes) payloads to write, and the clusters actually used.
    """
    runs: list[tuple[int, int | None]] = []
    writes: list[tuple[int, bytes]] = []
    lcn = first_lcn
    holes = 0
    for kind, payload in units:
        if kind == "sparse":
            holes += UNIT_CLUSTERS
            continue
        used = (len(payload) + BYTES_PER_CLUSTER - 1) // BYTES_PER_CLUSTER
        if holes:
            runs.append((holes, None))
            holes = 0
        runs.append((used, lcn))
        writes.append((lcn, payload))
        lcn += used
        holes += UNIT_CLUSTERS - used
    if holes:
        runs.append((holes, None))
    return runs, writes, lcn - first_lcn


def check_units(logical: bytes, units: list[tuple[str, bytes]]) -> None:
    """Prove every stored unit decodes back to the bytes it was made from."""
    for index, (kind, payload) in enumerate(units):
        start = index * UNIT_BYTES
        unit = logical[start : start + UNIT_BYTES].ljust(UNIT_BYTES, b"\x00")
        if kind == "sparse":
            assert not any(unit), "a sparse unit must be all zeros"
        elif kind == "raw":
            assert payload == unit, "a raw unit is stored verbatim"
        else:
            assert lznt1.decompress_unit(payload, UNIT_BYTES) == unit, "the unit must decode back"


def add_compressed_file(
    volume: NtfsVolume, number: int, name: str, logical: bytes, first_lcn: int, *, truncate: int = 0
) -> None:
    units = lznt1.classify_units(
        logical, cluster_size=BYTES_PER_CLUSTER, unit_clusters=UNIT_CLUSTERS
    )
    check_units(logical, units)
    runs, writes, allocated = compressed_runs(units, first_lcn)
    for lcn, payload in writes:
        volume.write_data(lcn, payload, allocated=False)
    if truncate:
        # A torn record can lose the cluster a chunk straddles, which leaves the stream shorter
        # than its own header claims.
        used, lcn = runs[0]
        runs[0] = (used - truncate, lcn)
        runs[1] = (runs[1][0] + truncate, None)
        allocated -= truncate
    volume.add_file(
        number,
        name,
        5,
        1,
        nonresident_attr(
            ATTR_DATA,
            1,
            runs,
            len(logical),
            len(logical),
            BYTES_PER_CLUSTER,
            flags=ATTR_FLAG_COMPRESSED,
            compression_unit=COMPRESSION_UNIT_BITS,
            allocated_clusters=allocated,
        ),
    )


