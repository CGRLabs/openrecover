#!/usr/bin/env python3
"""Build the deterministic FAT32 disk-image fixtures for the M1 gate.

The committed gzip images are authoritative for CI; this builder exists so the
images can be regenerated byte-for-byte. See docs/DECISIONS.md (2026-10-20,
"FAT32 fixtures use a deterministic Python builder") for why mkfs.fat/mtools
are not used.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import struct
import uuid
import zlib
from datetime import datetime, timezone
from pathlib import Path

import file_builders as media

SECTOR = 512
TOTAL_SECTORS = 16384
BYTES_PER_CLUSTER = 2048
SECTORS_PER_CLUSTER = BYTES_PER_CLUSTER // SECTOR
RESERVED_SECTORS = 32
NUM_FATS = 2
FAT_SECTORS = 32
DATA_START_SECTOR = RESERVED_SECTORS + NUM_FATS * FAT_SECTORS
CLUSTER_COUNT = (TOTAL_SECTORS - DATA_START_SECTOR) // SECTORS_PER_CLUSTER
FAT_ENTRIES = FAT_SECTORS * SECTOR // 4
VOLUME_BYTES = TOTAL_SECTORS * SECTOR
VOLUME_ID = 0x4F524331
VOLUME_LABEL = b"OPENRCVR   "
FAT_EOC = 0x0FFFFFFF
FAT_MEDIA = 0x0FFFFFF8

CRT = datetime(2023, 1, 2, 3, 4, 6, tzinfo=timezone.utc)
WRT = datetime(2024, 3, 5, 6, 7, 8, tzinfo=timezone.utc)
ACC = datetime(2024, 6, 7, 0, 0, 0, tzinfo=timezone.utc)

NOTE = "contiguous_assumption; fat_local_time_assumed_utc"


def fat_date(value: datetime) -> int:
    return ((value.year - 1980) << 9) | (value.month << 5) | value.day


def fat_time(value: datetime) -> int:
    return (value.hour << 11) | (value.minute << 5) | (value.second // 2)


def put16(buf: bytearray, off: int, value: int) -> None:
    struct.pack_into("<H", buf, off, value)


def put32(buf: bytearray, off: int, value: int) -> None:
    struct.pack_into("<I", buf, off, value)


def put64(buf: bytearray, off: int, value: int) -> None:
    struct.pack_into("<Q", buf, off, value)


def short_name_checksum(name: bytes) -> int:
    total = 0
    for char in name:
        total = (((total & 1) << 7) + (total >> 1) + char) & 0xFF
    return total


def lfn_entries(long_name: str, short_name: bytes, deleted: bool) -> list[bytes]:
    encoded = long_name.encode("utf-16-le")
    units = list(struct.unpack("<%dH" % (len(encoded) // 2), encoded))
    parts = (len(units) + 12) // 13
    checksum = short_name_checksum(short_name)
    out: list[bytes] = []
    for seq in range(parts, 0, -1):
        chunk = units[(seq - 1) * 13 : seq * 13]
        if len(chunk) < 13:
            chunk = chunk + [0x0000] + [0xFFFF] * (13 - len(chunk) - 1)
        raw = bytearray(32)
        raw[0] = seq | (0x40 if seq == parts else 0)
        raw[11] = 0x0F
        raw[13] = checksum
        for offset, count in ((1, 5), (14, 6), (28, 2)):
            for index in range(count):
                put16(raw, offset + index * 2, chunk.pop(0))
        if deleted:
            raw[0] = 0xE5
        out.append(bytes(raw))
    return out


def short_entry(
    name: bytes,
    attr: int,
    cluster: int,
    size: int,
    *,
    nt_res: int = 0,
    deleted: bool = False,
    timestamps: bool = True,
) -> bytes:
    assert len(name) == 11
    raw = bytearray(32)
    raw[0:11] = name
    raw[11] = attr
    raw[12] = nt_res
    if timestamps:
        put16(raw, 14, fat_time(CRT))
        put16(raw, 16, fat_date(CRT))
        put16(raw, 18, fat_date(ACC))
        put16(raw, 22, fat_time(WRT))
        put16(raw, 24, fat_date(WRT))
    put16(raw, 20, (cluster >> 16) & 0x0FFF)
    put16(raw, 26, cluster & 0xFFFF)
    put32(raw, 28, size)
    if deleted:
        raw[0] = 0xE5
    return bytes(raw)


def dot_entry(name: bytes, cluster: int) -> bytes:
    raw = bytearray(short_entry(name, 0x10, cluster, 0, timestamps=False))
    return bytes(raw)


def content_for(tag: str, size: int) -> bytes:
    stream = bytearray()
    counter = 0
    while len(stream) < size:
        stream += hashlib.sha256(f"{tag}:{counter}".encode("utf-8")).digest()
        counter += 1
    return bytes(stream[:size])


def unix_seconds(value: datetime) -> int:
    return int(value.timestamp())


class Fat32Volume:
    def __init__(self) -> None:
        self.img = bytearray(VOLUME_BYTES)
        self.fat = [0] * FAT_ENTRIES
        self.fat[0] = FAT_MEDIA
        self.fat[1] = 0x0FFFFFFF

    def cluster_offset(self, cluster: int) -> int:
        assert 2 <= cluster <= CLUSTER_COUNT + 1, cluster
        return (DATA_START_SECTOR + (cluster - 2) * SECTORS_PER_CLUSTER) * SECTOR

    def write_cluster(self, cluster: int, data: bytes) -> None:
        assert len(data) <= BYTES_PER_CLUSTER
        offset = self.cluster_offset(cluster)
        self.img[offset : offset + len(data)] = data

    def allocate(self, first: int, count: int) -> None:
        for index in range(count):
            self.fat[first + index] = first + index + 1 if index + 1 < count else FAT_EOC

    def write_file(self, first: int, data: bytes, *, allocated: bool) -> None:
        if not data:
            return
        count = (len(data) + BYTES_PER_CLUSTER - 1) // BYTES_PER_CLUSTER
        if allocated:
            self.allocate(first, count)
        for index in range(count):
            chunk = data[index * BYTES_PER_CLUSTER : (index + 1) * BYTES_PER_CLUSTER]
            self.write_cluster(first + index, chunk)

    def write_directory(self, cluster: int, entries: list[bytes]) -> None:
        raw = b"".join(entries)
        assert len(raw) <= BYTES_PER_CLUSTER
        self.write_cluster(cluster, raw + b"\x00" * (BYTES_PER_CLUSTER - len(raw)))

    def finalize_boot(self) -> None:
        boot = bytearray(512)
        boot[0:3] = b"\xEB\x58\x90"
        boot[3:11] = b"MSWIN4.1"
        put16(boot, 0x0B, SECTOR)
        boot[0x0D] = SECTORS_PER_CLUSTER
        put16(boot, 0x0E, RESERVED_SECTORS)
        boot[0x10] = NUM_FATS
        boot[0x15] = 0xF8
        put16(boot, 0x18, 63)
        put16(boot, 0x1A, 255)
        put32(boot, 0x20, TOTAL_SECTORS)
        put32(boot, 0x24, FAT_SECTORS)
        put32(boot, 0x2C, 2)
        put16(boot, 0x30, 1)
        put16(boot, 0x32, 6)
        boot[0x40] = 0x80
        boot[0x42] = 0x29
        put32(boot, 0x43, VOLUME_ID)
        boot[0x47:0x52] = VOLUME_LABEL
        boot[0x52:0x5A] = b"FAT32   "
        boot[0x1FE] = 0x55
        boot[0x1FF] = 0xAA
        self.img[0:SECTOR] = boot
        self.img[6 * SECTOR : 7 * SECTOR] = boot

        free_clusters = sum(1 for value in self.fat[2 : CLUSTER_COUNT + 2] if value == 0)
        fsinfo = bytearray(512)
        put32(fsinfo, 0, 0x41615252)
        put32(fsinfo, 484, 0x61417272)
        put32(fsinfo, 488, free_clusters)
        put32(fsinfo, 492, 0xFFFFFFFF)
        put32(fsinfo, 508, 0xAA550000)
        self.img[1 * SECTOR : 2 * SECTOR] = fsinfo
        self.img[7 * SECTOR : 8 * SECTOR] = fsinfo

        fat_bytes = bytearray(FAT_SECTORS * SECTOR)
        for index, value in enumerate(self.fat):
            put32(fat_bytes, index * 4, value)
        for copy in range(NUM_FATS):
            start = (RESERVED_SECTORS + copy * FAT_SECTORS) * SECTOR
            self.img[start : start + len(fat_bytes)] = fat_bytes


def sorted_files(entries: list[dict]) -> list[dict]:
    return sorted(entries, key=lambda entry: entry["path"])


def recovered_entry(
    path: str,
    size: int,
    cluster: int,
    *,
    low: bool = False,
    guessed_first_char: bool = False,
) -> dict:
    extents = []
    if size:
        extents.append(
            {
                "offset_bytes": (DATA_START_SECTOR + (cluster - 2) * SECTORS_PER_CLUSTER) * SECTOR,
                "length_bytes": size,
                "sparse": False,
            }
        )
    flags = ["ClustersReallocated"] if low else []
    if guessed_first_char:
        flags.append("NameFirstCharGuessed")
    flags.sort()
    return {
        "path": path,
        "name": path.rsplit("/", 1)[-1],
        "size_bytes": size,
        "extents": extents,
        "confidence": "low" if low else "high",
        "flags": flags,
        "note": NOTE,
        "mtime_unix": unix_seconds(WRT),
        "ctime_unix": unix_seconds(CRT),
        "atime_unix": unix_seconds(ACC),
        "origin": "filesystem_metadata",
    }


def build_basic() -> tuple[bytes, list[dict], dict[str, str]]:
    # A real JPEG gives the M3 dedup test a carved hit that also has FS metadata.
    deleted_photo = media.build_jpeg(entropy_size=300)
    volume = Fat32Volume()
    root: list[bytes] = [short_entry(VOLUME_LABEL, 0x08, 0, 0, timestamps=False)]
    docs: list[bytes] = [dot_entry(b".          ", 3), dot_entry(b"..         ", 2)]
    pics: list[bytes] = [dot_entry(b".          ", 4), dot_entry(b"..         ", 2)]
    year2024: list[bytes] = [dot_entry(b".          ", 5), dot_entry(b"..         ", 4)]
    old_stuff: list[bytes] = [dot_entry(b".          ", 6), dot_entry(b"..         ", 2)]
    originals: dict[str, str] = {}

    def add_file(
        directory: list[bytes],
        short: bytes,
        long_name: str | None,
        cluster: int,
        data: bytes,
        *,
        deleted: bool,
    ) -> None:
        if long_name:
            directory.extend(lfn_entries(long_name, short, deleted))
        directory.append(
            short_entry(
                short,
                0x20,
                cluster,
                len(data),
                nt_res=0x18 if deleted and not long_name else 0,
                deleted=deleted,
            )
        )
        if data:
            volume.write_file(cluster, data, allocated=not deleted)

    def add_dir(
        directory: list[bytes], short: bytes, long_name: str | None, cluster: int, *, deleted: bool
    ) -> None:
        if long_name:
            directory.extend(lfn_entries(long_name, short, deleted))
        directory.append(short_entry(short, 0x10, cluster, 0, deleted=deleted))

    # Live files and directories.
    add_file(root, b"README  TXT", None, 10, content_for("readme.txt", 40), deleted=False)
    add_dir(root, b"DOCS       ", None, 3, deleted=False)
    add_dir(root, b"PICS       ", None, 4, deleted=False)

    # Deleted root-level files: two short-only names, one zero-length file.
    add_file(root, b"PLAIN   TXT", None, 14, content_for("plain.txt", 3000), deleted=True)
    add_file(root, b"NOTES   TXT", None, 16, content_for("notes.txt", 10), deleted=True)
    add_file(root, b"EMPTY   TXT", None, 0, b"", deleted=True)

    # Deleted directory with two deleted children.
    add_dir(root, b"OLDSTU~1   ", "Old Stuff", 6, deleted=True)
    add_file(old_stuff, b"INNER1~1BIN", "inner one.bin", 26, content_for("inner one.bin", 2048), deleted=True)
    add_file(old_stuff, b"INNER2~1BIN", "inner two.bin", 27, content_for("inner two.bin", 700), deleted=True)

    add_file(
        docs,
        b"QUARTE~1TXT",
        "Quarterly results.txt",
        11,
        content_for("Quarterly results.txt", 1800),
        deleted=False,
    )
    add_file(
        docs,
        b"QUARTE~2TXT",
        "Quarterly report 2024.txt",
        17,
        content_for("Quarterly report 2024.txt", 5000),
        deleted=True,
    )
    add_file(
        docs,
        b"UNICOD~1PDF",
        "Ünïcødé résumé.pdf",
        20,
        content_for("Unicode resume", 1200),
        deleted=True,
    )

    add_dir(pics, b"2024       ", None, 5, deleted=False)
    add_file(
        year2024,
        b"ANHDEP~1JPG",
        "Ω-ảnh đẹp.jpg",
        12,
        content_for("Omega photo", 2500),
        deleted=False,
    )
    add_file(
        year2024,
        b"SUMMER~1JPG",
        "summer holiday photo.jpg",
        21,
        deleted_photo,
        deleted=True,
    )
    add_file(year2024, b"DATA    CSV", None, 25, content_for("data.csv", 100), deleted=True)

    volume.write_directory(2, root)
    volume.write_directory(3, docs)
    volume.write_directory(4, pics)
    volume.write_directory(5, year2024)
    volume.write_directory(6, old_stuff)
    for directory_cluster in (2, 3, 4, 5):
        volume.allocate(directory_cluster, 1)
    assert volume.fat[6] == 0
    volume.finalize_boot()

    files = [
        recovered_entry("_lain.txt", 3000, 14, guessed_first_char=True),
        recovered_entry("_otes.txt", 10, 16, guessed_first_char=True),
        recovered_entry("_mpty.txt", 0, 0, guessed_first_char=True),
        recovered_entry("DOCS/Quarterly report 2024.txt", 5000, 17),
        recovered_entry("DOCS/Ünïcødé résumé.pdf", 1200, 20),
        recovered_entry("PICS/2024/summer holiday photo.jpg", len(deleted_photo), 21),
        recovered_entry("PICS/2024/_ata.csv", 100, 25, guessed_first_char=True),
        recovered_entry("Old Stuff/inner one.bin", 2048, 26),
        recovered_entry("Old Stuff/inner two.bin", 700, 27),
    ]

    originals["plain.txt"] = hashlib.sha256(content_for("plain.txt", 3000)).hexdigest()
    originals["notes.txt"] = hashlib.sha256(content_for("notes.txt", 10)).hexdigest()
    originals["empty.txt"] = hashlib.sha256(b"").hexdigest()
    originals["Quarterly report 2024.txt"] = hashlib.sha256(
        content_for("Quarterly report 2024.txt", 5000)
    ).hexdigest()
    originals["Unicode resume"] = hashlib.sha256(content_for("Unicode resume", 1200)).hexdigest()
    originals["summer holiday photo.jpg"] = hashlib.sha256(deleted_photo).hexdigest()
    originals["data.csv"] = hashlib.sha256(content_for("data.csv", 100)).hexdigest()
    originals["inner one.bin"] = hashlib.sha256(content_for("inner one.bin", 2048)).hexdigest()
    originals["inner two.bin"] = hashlib.sha256(content_for("inner two.bin", 700)).hexdigest()

    hashes = {}
    for golden, key in zip(
        files,
        [
            "plain.txt",
            "notes.txt",
            "empty.txt",
            "Quarterly report 2024.txt",
            "Unicode resume",
            "summer holiday photo.jpg",
            "data.csv",
            "inner one.bin",
            "inner two.bin",
        ],
    ):
        hashes[golden["path"]] = originals[key]
    return bytes(volume.img), files, hashes


def build_reused() -> tuple[bytes, list[dict], dict[str, str]]:
    volume = Fat32Volume()
    root = [short_entry(VOLUME_LABEL, 0x08, 0, 0, timestamps=False)]

    root.extend(lfn_entries("new data.bin", b"NEWDAT~1BIN", False))
    root.append(short_entry(b"NEWDAT~1BIN", 0x20, 7, 4096))
    volume.write_file(7, content_for("new data.bin", 4096), allocated=True)

    root.extend(lfn_entries("Reused report.docx", b"REUSED~1DOC", True))
    root.append(short_entry(b"REUSED~1DOC", 0x20, 7, 4096, deleted=True))

    root.append(short_entry(b"KEEP    TXT", 0x20, 9, 100, nt_res=0x18, deleted=True))
    volume.write_file(9, content_for("keep.txt", 100), allocated=False)

    volume.write_directory(2, root)
    volume.allocate(2, 1)
    volume.finalize_boot()

    files = [
        recovered_entry("Reused report.docx", 4096, 7, low=True),
        recovered_entry("_eep.txt", 100, 9, guessed_first_char=True),
    ]
    hashes = {"_eep.txt": hashlib.sha256(content_for("keep.txt", 100)).hexdigest()}
    return bytes(volume.img), files, hashes


def build_mbr(volume: bytes) -> bytes:
    container = bytearray(2048 * SECTOR + len(volume))
    mbr = bytearray(SECTOR)
    entry = 0x1BE
    mbr[entry + 4] = 0x0C
    put32(mbr, entry + 8, 2048)
    put32(mbr, entry + 12, TOTAL_SECTORS)
    mbr[510] = 0x55
    mbr[511] = 0xAA
    container[0:SECTOR] = mbr
    container[2048 * SECTOR :] = volume
    return bytes(container)


def gpt_header(
    current_lba: int,
    backup_lba: int,
    entry_lba: int,
    disk_guid: uuid.UUID,
    entries_crc: int,
    last_usable_lba: int,
) -> bytes:
    header = bytearray(SECTOR)
    header[0:8] = b"EFI PART"
    put32(header, 8, 0x00010000)
    put32(header, 12, 92)
    put32(header, 16, 0)
    put64(header, 24, current_lba)
    put64(header, 32, backup_lba)
    put64(header, 40, 34)
    put64(header, 48, last_usable_lba)
    header[56:72] = disk_guid.bytes_le
    put64(header, 72, entry_lba)
    put32(header, 80, 128)
    put32(header, 84, 128)
    put32(header, 88, entries_crc)
    put32(header, 16, zlib.crc32(header[:92]) & 0xFFFFFFFF)
    return bytes(header)


CURRENT_LAST_LBA = 18464


def build_gpt(volume: bytes) -> bytes:
    last_lba = CURRENT_LAST_LBA
    entry_lba = 2
    backup_entries_lba = 18432
    assert entry_lba + 32 <= 2048
    assert 2048 + TOTAL_SECTORS - 1 == 18431
    assert backup_entries_lba + 32 == last_lba

    container = bytearray((last_lba + 1) * SECTOR)
    mbr = bytearray(SECTOR)
    entry = 0x1BE
    mbr[entry + 4] = 0xEE
    put32(mbr, entry + 8, 1)
    put32(mbr, entry + 12, min(last_lba, 0xFFFFFFFF))
    mbr[510] = 0x55
    mbr[511] = 0xAA
    container[0:SECTOR] = mbr

    disk_guid = uuid.UUID("4f524356-0001-4000-8000-4f50454e5243")
    part_guid = uuid.UUID("4f524356-0002-4000-8000-4f50454e5243")
    type_guid = uuid.UUID("ebd0a0a2-b9e5-4433-87c0-68b6b72699c7")

    entries = bytearray(128 * 128)
    entries[0:16] = type_guid.bytes_le
    entries[16:32] = part_guid.bytes_le
    put64(entries, 32, 2048)
    put64(entries, 40, 2048 + TOTAL_SECTORS - 1)
    name = "OpenRecover FAT32".encode("utf-16-le")
    entries[56 : 56 + len(name)] = name
    entries_crc = zlib.crc32(entries) & 0xFFFFFFFF
    entry_sectors = len(entries) // SECTOR

    container[entry_lba * SECTOR : entry_lba * SECTOR + len(entries)] = entries
    container[backup_entries_lba * SECTOR : backup_entries_lba * SECTOR + len(entries)] = entries

    primary = gpt_header(1, last_lba, entry_lba, disk_guid, entries_crc, backup_entries_lba - 1)
    backup = gpt_header(
        last_lba, 1, backup_entries_lba, disk_guid, entries_crc, backup_entries_lba - 1
    )
    container[SECTOR : 2 * SECTOR] = primary
    container[last_lba * SECTOR : (last_lba + 1) * SECTOR] = backup

    volume_offset = 2048 * SECTOR
    container[volume_offset : volume_offset + len(volume)] = volume
    assert volume_offset + len(volume) <= last_lba * SECTOR
    assert entry_sectors == 32
    return bytes(container)


def write_gzip(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9) as gz:
            gz.write(data)


def write_json(path: Path, document: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False)
    path.write_text(text + "\n", encoding="utf-8")


def golden_document(image_name: str, image: bytes, files: list[dict], hashes: dict[str, str]) -> dict:
    return {
        "image": image_name,
        "image_sha256": hashlib.sha256(image).hexdigest(),
        "volume_bytes": VOLUME_BYTES,
        "files": sorted_files(files),
        "hashes": dict(sorted(hashes.items())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    repo = Path(__file__).resolve().parents[2]
    parser.add_argument("--images", type=Path, default=repo / "tests/fixtures/images")
    parser.add_argument("--golden", type=Path, default=repo / "tests/fixtures/golden")
    args = parser.parse_args()

    basic, basic_files, basic_hashes = build_basic()
    reused, reused_files, reused_hashes = build_reused()

    documents = {
        "fat32_basic": golden_document("fat32_basic.img", basic, basic_files, basic_hashes),
        "fat32_reused": golden_document("fat32_reused.img", reused, reused_files, reused_hashes),
    }
    images = {
        "fat32_basic.img": basic,
        "fat32_reused.img": reused,
        "fat32_in_mbr.img": build_mbr(basic),
        "fat32_in_gpt.img": build_gpt(basic),
    }

    for name, image in images.items():
        write_gzip(args.images / (name + ".gz"), image)
    for name, document in documents.items():
        write_json(args.golden / (name + ".golden.json"), document)

    print(f"wrote {len(images)} images to {args.images}")
    print(f"wrote {len(documents)} goldens to {args.golden}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
