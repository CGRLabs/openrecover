def expectation(spec: dict, reuse_all: bool) -> dict:
    notes = list(NAME_NOTES[spec["name_state"]])
    flags: list[str] = []
    if spec["name_state"] != "paired":
        flags.append("PathUncertain")
    if spec.get("bad_csum"):
        notes.append("inode_checksum_mismatch")
    if spec.get("encrypted"):
        notes.append("encrypted_content")
        flags.append("Unsupported")

    reused = spec.get("always_reused", False) or (reuse_all and spec["packed"])
    if reused:
        notes.append("data_blocks_reused_or_outside_volume")
        flags.append("ClustersReallocated")
    elif spec.get("holes"):
        notes.append("contains_holes_or_unwritten_extents")

    if spec.get("encrypted"):
        confidence = "high"
    elif spec.get("bad_csum"):
        confidence = "low" if reused else "medium"
    else:
        confidence = "low" if reused else "high"

    data: bytes | None = None
    if not spec.get("encrypted"):
        data = spec["inline"] if "inline" in spec else file_bytes(spec["blocks"], spec["size"])
    return {
        "path": spec["path"],
        "name": spec["path"].rsplit("/", 1)[-1],
        "size_bytes": spec["size"],
        "sha256": None if data is None else hashlib.sha256(data).hexdigest(),
        "confidence": confidence,
        "flags": sorted(set(flags)),
        "note_contains": sorted(notes),
        "deleted_unix": spec["deleted_unix"],
        "mtime_unix": spec["mtime_unix"],
        "inode": spec["ino"],
    }


