import json
import struct
from pathlib import Path

BLOCK = 1024
BLOCKS_PER_GROUP = 128
GROUPS = 2
BLOCKS_COUNT = BLOCKS_PER_GROUP * GROUPS  # 256
INODES_PER_GROUP = 16
INODES_COUNT = INODES_PER_GROUP * GROUPS  # 32
INODE_SIZE = 256
EXTRA_ISIZE = 32
DESC_SIZE = 32
VOLUME_BYTES = BLOCKS_COUNT * BLOCK
FIRST_DATA_BLOCK = 0  # 1 KiB blocks number data from block 0
UUID = bytes([0xA0 + i for i in range(16)])

SUPER_BLOCK = 1
GDT_BLOCK = 2
GROUP0_BLOCK_BITMAP = 3
GROUP0_INODE_BITMAP = 4
GROUP0_INODE_TABLE = 5  # 16 inodes * 256 bytes = 4 blocks
GROUP1_BLOCK_BITMAP = 128
GROUP1_INODE_BITMAP = 129
GROUP1_INODE_TABLE = 130

ROOT_BLOCK = 10
SUB_BLOCK = 11
MISC_BLOCK = 12

# Inode numbers.
ROOT_INO = 2
NOTES_INO = 11
SUB_INO = 12
MISC_INO = 13
SECRET_INO = 14
KEEP_INO = 15
