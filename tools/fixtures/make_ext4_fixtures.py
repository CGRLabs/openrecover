#!/usr/bin/env python3
"""Build the deterministic ext4 disk-image fixtures for the 1.2.0 filesystem-breadth gate.

The committed gzip image is authoritative for CI; this builder exists so it can be
regenerated byte-for-byte on another host. mkfs.ext4 and e2fsprogs are unavailable on the
development host and would not guarantee identical images, so the volume is written a field
at a time from the on-disk layout in
`libopenrecover/include/openrecover/fs/ext4/ext4_boot.hpp`.

Every checksum the parser can verify is computed here with the same chained CRC32c the
kernel and e2fsprogs use for metadata_csum volumes: a raw running state, the 2 bytes of
i_checksum_lo (and of i_checksum_hi, and of bg_checksum) folded away as zeros, and the
low 16 bits stored for a group descriptor. A fixture that disagrees with the reader fails
instead of drifting.

Deletion is modelled the way ext4 actually performs it: unlink() zeroes only the directory
record's inode field, folds that record's length into the record before it -- which is why a
deleted name survives inside a longer live record's slack -- and clears i_links_count while
leaving i_mode, i_size and the block map in place. Only i_dtime and the containing
directory's i_mtime connect a name to a body, so the fixture deliberately contains one
deletion second shared by two names and two inodes: the reader has to report that pair as
ambiguous rather than guess.
"""

