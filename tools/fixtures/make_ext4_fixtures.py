# Superblock field offsets.
S_INODES_COUNT, S_BLOCKS_COUNT_LO, S_BLOCKS_COUNT_HI = 0, 4, 336
S_FIRST_DATA_BLOCK, S_LOG_BLOCK_SIZE = 20, 24
S_BLOCKS_PER_GROUP, S_INODES_PER_GROUP = 32, 40
S_MTIME, S_MNT_COUNT, S_MAGIC, S_STATE, S_ERRORS = 44, 52, 56, 58, 60
