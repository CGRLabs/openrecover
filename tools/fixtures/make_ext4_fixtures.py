BG_FLAGS, BG_ITALY_UNUSED, BG_CHECKSUM = 18, 28, 30

# Extents.
EXT_HEADER_BYTES, EXT_ENTRY_BYTES = 12, 12
EXT_MAGIC = 0xF30A
EXT_UNWRITTEN_BIT = 0x8000

# Directory records.
DIR_INODE, DIR_REC_LEN, DIR_NAME_LEN, DIR_FILE_TYPE, DIR_NAME = 0, 4, 6, 7, 8
DIR_PAD = 3
TYPE_REGULAR, TYPE_DIR, TYPE_CSUM = 1, 2, 0xDE


# --------------------------------------------------------------------------
# CRC32c (reflected Castagnoli), chained on the raw register state exactly as
# ext4's metadata_csum seeds are chained.
# --------------------------------------------------------------------------
def _crc32c_table() -> list[int]:
    poly = 0x82F63B78
    table = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ poly if c & 1 else c >> 1
        table.append(c)
    return table


CRC32C = _crc32c_table()


def crc32c_continue(state: int, data: bytes) -> int:
    for byte in data:
        state = CRC32C[(state ^ byte) & 0xFF] ^ (state >> 8)
    return state & 0xFFFFFFFF


def crc32c_zeros(state: int, count: int) -> int:
    for _ in range(count):
        state = CRC32C[state & 0xFF] ^ (state >> 8)
    return state & 0xFFFFFFFF


def crc32c_raw(data: bytes) -> int:
    return crc32c_continue(0xFFFFFFFF, data)


# --------------------------------------------------------------------------
# Byte writers
# --------------------------------------------------------------------------
def put8(buf: bytearray, off: int, value: int) -> None:
    buf[off] = value & 0xFF


def put16(buf: bytearray, off: int, value: int) -> None:
    buf[off:off + 2] = struct.pack("<H", value & 0xFFFF)


def put32(buf: bytearray, off: int, value: int) -> None:
    buf[off:off + 4] = struct.pack("<I", value & 0xFFFFFFFF)


def put64(buf: bytearray, off: int, value: int) -> None:
    buf[off:off + 8] = struct.pack("<Q", value & 0xFFFFFFFFFFFFFFFF)


def block_byte(blk: int) -> int:
    return blk * BLOCK


def inode_byte(ino: int) -> int:
    table = GROUP0_INODE_TABLE if ino <= INODES_PER_GROUP else GROUP1_INODE_TABLE
    return block_byte(table) + ((ino - 1) % INODES_PER_GROUP) * INODE_SIZE


def descriptor_byte(group: int) -> int:
    return block_byte(GDT_BLOCK) + group * DESC_SIZE


def block_bit_byte(blk: int) -> int:
    bitmap = GROUP0_BLOCK_BITMAP if blk < BLOCKS_PER_GROUP else GROUP1_BLOCK_BITMAP
    return block_byte(bitmap) + (blk % BLOCKS_PER_GROUP) // 8


def inode_bit_byte(ino: int) -> int:
    bitmap = GROUP0_INODE_BITMAP if ino <= INODES_PER_GROUP else GROUP1_INODE_BITMAP
    return block_byte(bitmap) + ((ino - 1) % INODES_PER_GROUP) // 8


def content(blk: int, take: int = BLOCK) -> bytes:
    """The bytes this builder writes into data block `blk`."""
    return bytes([(blk * 131 + i * 17) & 0xFF for i in range(take)])


def own_size(name: str) -> int:
    return DIR_NAME + ((len(name) + DIR_PAD) & ~DIR_PAD)


class Volume:
    def __init__(self, *, reuse_all: bool = False) -> None:
        self.buf = bytearray(VOLUME_BYTES)
        self.reuse_all = reuse_all
        self.seed = crc32c_raw(UUID)
        self.allocated_blocks: set[int] = set()
        self.allocated_inodes: set[int] = set()
        self.inodes: dict[int, dict] = {}
        self.build()

    # ---- allocation -----------------------------------------------------
    def mark_block(self, blk: int) -> None:
        self.allocated_blocks.add(blk)

    def mark_inode(self, ino: int) -> None:
        self.allocated_inodes.add(ino)

    # ---- directory blocks -----------------------------------------------
    def write_dir(self, blk: int, records: list[tuple[int, int, int, str, int]]) -> None:
        """records: (offset in block, inode, file type, name, rec_len).

        Offsets are explicit because a deleted record does not follow the record before it:
        unlink() gave that record the deleted one's length, so the deleted name lives in the
        slack the lengthened record now claims.
        """
        base = block_byte(blk)
        for at, ino, ftype, name, rec_len in records:
            needed = own_size(name)
            assert rec_len >= needed, f"{name} is longer than its record"
            assert at + rec_len <= BLOCK, f"{name} runs past the block"
            off = base + at
            put32(self.buf, off + DIR_INODE, ino)
            put16(self.buf, off + DIR_REC_LEN, rec_len)
            put8(self.buf, off + DIR_NAME_LEN, len(name))
            put8(self.buf, off + DIR_FILE_TYPE, ftype)
            self.buf[off + DIR_NAME:off + DIR_NAME + len(name)] = name.encode()
        self.mark_block(blk)

    # ---- inodes ---------------------------------------------------------
    def extent_area(self, leaves: list[tuple[int, int, int, bool]], gen: int) -> bytes:
        area = bytearray(BLOCK_AREA_BYTES)
        put16(area, 0, EXT_MAGIC)
        put16(area, 2, len(leaves))
        put16(area, 4, 4)
        put16(area, 6, 0)
        put32(area, 8, gen)
        for index, (first, length, start, unwritten) in enumerate(leaves):
            e = EXT_HEADER_BYTES + index * EXT_ENTRY_BYTES
            put32(area, e + 0, first)
            raw_len = length + (EXT_UNWRITTEN_BIT if unwritten else 0)
            put16(area, e + 4, raw_len)
            put16(area, e + 6, start >> 16)
            put32(area, e + 8, start)
        return bytes(area)

    def indirect_area(self, direct: list[int | None], index_block: int) -> bytes:
        area = bytearray(BLOCK_AREA_BYTES)
        for slot, blk in enumerate(direct):
            if blk is not None:
                put32(area, slot * 4, blk)
        put32(area, 12 * 4, index_block)
        return bytes(area)

    def inline_area(self, payload: bytes) -> bytes:
        area = bytearray(BLOCK_AREA_BYTES)
        put16(area, 0, EXT_MAGIC)
        put16(area, 2, 0)
        put16(area, 4, 1)
        put16(area, 6, 0)
        put32(area, 8, 0x5150)
        area[EXT_HEADER_BYTES:EXT_HEADER_BYTES + len(payload)] = payload
        return bytes(area)

    def add_inode(self, ino: int, *, mode: int, links: int, dtime: int, mtime: int,
                  size: int, blocks512: int, flags: int, gen: int, area: bytes) -> None:
        self.inodes[ino] = {
            "mode": mode, "links": links, "dtime": dtime, "mtime": mtime, "size": size,
            "blocks512": blocks512, "flags": flags, "gen": gen, "area": area,
        }
        if links > 0 or dtime == 0:
            self.mark_inode(ino)

    def write_inodes(self) -> None:
        for ino, fields in self.inodes.items():
            off = inode_byte(ino)
            rec = bytearray(INODE_SIZE)
            put16(rec, I_MODE, fields["mode"])
            put16(rec, I_UID, 1000)
            put16(rec, I_GID, 1000)
            put32(rec, I_SIZE_LO, fields["size"] & 0xFFFFFFFF)
            put32(rec, I_SIZE_HI, fields["size"] >> 32)
            put32(rec, I_ATIME, 1700000000)
            put32(rec, I_CTIME, 1700000001)
            put32(rec, I_MTIME, fields["mtime"])
            put32(rec, I_DTIME, fields["dtime"])
            put16(rec, I_LINKS, fields["links"])
            put32(rec, I_BLOCKS, fields["blocks512"])
            put16(rec, I_BLOCKS_HI, 0)
            put32(rec, I_FLAGS, fields["flags"])
            put32(rec, I_GEN, fields["gen"])
            put16(rec, I_EXTRA_ISIZE, EXTRA_ISIZE)
            put32(rec, I_CRTIME, fields["mtime"])
            rec[I_BLOCK:I_BLOCK + BLOCK_AREA_BYTES] = fields["area"]
            csum = self.inode_csum(rec, ino)
            put16(rec, I_CSUM_LO, csum & 0xFFFF)
            put16(rec, I_CSUM_HI, csum >> 16)
            if ino == BADCSUM_INO:
                put16(rec, I_CSUM_LO, (csum + 0x1111) & 0xFFFF)
            self.buf[off:off + INODE_SIZE] = rec

    def inode_csum(self, rec: bytearray, ino: int) -> int:
        state = crc32c_continue(self.seed, struct.pack("<I", ino))
        state = crc32c_continue(state, struct.pack("<I", self.inodes[ino]["gen"]))
        state = crc32c_continue(state, bytes(rec[:I_CSUM_LO]))
        state = crc32c_zeros(state, 2)
        state = crc32c_continue(state, bytes(rec[I_CSUM_LO + 2:128]))
        state = crc32c_continue(state, bytes(rec[128:I_CSUM_HI]))
        state = crc32c_zeros(state, 2)
        state = crc32c_continue(state, bytes(rec[I_CSUM_HI + 2:INODE_SIZE]))
        return state

    # ---- metadata -------------------------------------------------------
    def write_superblock(self) -> None:
        off = block_byte(SUPER_BLOCK)
        s = bytearray(1024)
        put32(s, S_INODES_COUNT, INODES_COUNT)
        put32(s, S_BLOCKS_COUNT_LO, BLOCKS_COUNT)
        put32(s, S_FIRST_DATA_BLOCK, FIRST_DATA_BLOCK)
        put32(s, S_LOG_BLOCK_SIZE, 0)  # 1024 << 0
        put32(s, S_BLOCKS_PER_GROUP, BLOCKS_PER_GROUP)
        put32(s, S_INODES_PER_GROUP, INODES_PER_GROUP)
        put32(s, S_MTIME, 1700000000)
        put16(s, S_MNT_COUNT, 3)
        put16(s, S_MAGIC, S_MAGIC_VALUE)
        put16(s, S_STATE, 1)
        put16(s, S_ERRORS, 1)
        put32(s, S_CREATOR_OS, 0)
        put32(s, S_REV_LEVEL, 1)
        put32(s, S_FIRST_INO, 11)
        put16(s, S_INODE_SIZE, INODE_SIZE)
        put16(s, S_BLOCK_GROUP_NR, 0)
        put32(s, S_FEATURE_COMPAT,
              F_COMPAT_DIR_INDEX | F_COMPAT_EXT_ATTR | F_COMPAT_SPARSE_SUPER2)
        put32(s, S_FEATURE_INCOMPAT,
              F_INCOMPAT_FILETYPE | F_INCOMPAT_EXTENTS | F_INCOMPAT_CSUM_SEED)
        put32(s, S_FEATURE_RO_COMPAT, F_RO_EXTRA_ISIZE | F_RO_DIR_NLINK | F_RO_METADATA_CSUM)
        s[S_UUID:S_UUID + 16] = UUID
        s[S_VOLUME_NAME:S_VOLUME_NAME + 7] = b"orcrecov"[:7]
        s[S_LAST_MOUNTED:S_LAST_MOUNTED + 11] = b"/mnt/ext4fx"
        put32(s, S_JOURNAL_INO, 8)
        put16(s, S_DESC_SIZE, DESC_SIZE)
        put8(s, S_LOG_GROUPS_PER_FLEX, 0)
        put8(s, S_CHECKSUM_TYPE, 1)  # crc32c
        put32(s, S_CHECKSUM_SEED, self.seed)
        # s_checksum covers the superblock as it stands, with its own bytes read as zero.
        put32(s, S_CHECKSUM, crc32c_raw(bytes(s[:S_CHECKSUM])))
        self.buf[off:off + 1024] = s
        self.mark_block(SUPER_BLOCK)

    def write_descriptors(self) -> None:
        bitmaps = [GROUP0_BLOCK_BITMAP, GROUP1_BLOCK_BITMAP]
        inode_bitmaps = [GROUP0_INODE_BITMAP, GROUP1_INODE_BITMAP]
        tables = [GROUP0_INODE_TABLE, GROUP1_INODE_TABLE]
        for group in range(GROUPS):
            off = descriptor_byte(group)
            desc = bytearray(DESC_SIZE)
            put32(desc, BG_BLOCK_BITMAP, bitmaps[group])
            put32(desc, BG_INODE_BITMAP, inode_bitmaps[group])
            put32(desc, BG_INODE_TABLE, tables[group])
            put16(desc, BG_USED_DIRS, 3 if group == 0 else 0)
            put16(desc, BG_ITALY_UNUSED, 0)
            first = group * BLOCKS_PER_GROUP
            last = min(first + BLOCKS_PER_GROUP, BLOCKS_COUNT)
            used = sum(1 for blk in self.allocated_blocks if first <= blk < last)
            put16(desc, BG_FREE_BLOCKS, last - first - used)
            i_first = group * INODES_PER_GROUP + 1
            i_last = min(i_first + INODES_PER_GROUP, INODES_COUNT + 1)
            used_inodes = sum(1 for ino in self.allocated_inodes if i_first <= ino < i_last)
            put16(desc, BG_FREE_INODES, (i_last - i_first) - used_inodes)
            csum = crc32c_continue(self.seed, struct.pack("<I", group))
            csum = crc32c_continue(csum, bytes(desc[:BG_CHECKSUM]))
            csum = crc32c_zeros(csum, 2)
            put16(desc, BG_CHECKSUM, csum & 0xFFFF)
            self.buf[off:off + DESC_SIZE] = desc

    def write_bitmaps(self) -> None:
        for blk in self.allocated_blocks:
            self.buf[block_bit_byte(blk)] |= 1 << (blk % 8)
        for ino in self.allocated_inodes:
            self.buf[inode_bit_byte(ino)] |= 1 << ((ino - 1) % 8)

    # ---- the volume -----------------------------------------------------
    def build(self) -> None:
        # Metadata first: the group descriptors count the blocks the volume claims, and the
        # bitmap and inode-table blocks are part of that count.
        for blk in (SUPER_BLOCK, GDT_BLOCK, GROUP0_BLOCK_BITMAP, GROUP0_INODE_BITMAP,
                    GROUP1_BLOCK_BITMAP, GROUP1_INODE_BITMAP):
            self.mark_block(blk)
        for offset in range(INODE_SIZE * INODES_PER_GROUP // BLOCK + 1):
            self.mark_block(GROUP0_INODE_TABLE + offset)
            self.mark_block(GROUP1_INODE_TABLE + offset)
        self.write_directories()
        self.write_live_files()
        self.write_deleted_files()
        self.write_inodes()
        self.write_data_blocks()
        self.write_superblock()
        self.write_descriptors()
        self.write_bitmaps()

    def write_directories(self) -> None:
        # Root: notes.txt is live and its record absorbed the length of the removed
        # secret.txt, whose name still sits in that record's slack.
        self.write_dir(ROOT_BLOCK, [
            (0, ROOT_INO, TYPE_DIR, ".", 12),
            (12, ROOT_INO, TYPE_DIR, "..", 12),
            (24, NOTES_INO, TYPE_REGULAR, "notes.txt", 40),
            (44, 0, TYPE_REGULAR, "secret.txt", 20),
            (64, SUB_INO, TYPE_DIR, "subdir", 16),
            (80, MISC_INO, TYPE_DIR, "misc", BLOCK - 80),
        ])
        self.write_dir(SUB_BLOCK, [
            (0, SUB_INO, TYPE_DIR, ".", 12),
            (12, ROOT_INO, TYPE_DIR, "..", 32),
            (24, 0, TYPE_REGULAR, "photo.jpg", 20),
            (44, KEEP_INO, TYPE_REGULAR, "keep.dat", BLOCK - 44),
        ])
        # Two removals in the same second leave both names in "..'s slack; neither can be
        # matched to a body without guessing, which the reader has to say out loud.
        self.write_dir(MISC_BLOCK, [
            (0, MISC_INO, TYPE_DIR, ".", 12),
            (12, ROOT_INO, TYPE_DIR, "..", 44),
            (24, 0, TYPE_REGULAR, "a.bin", 16),
            (40, 0, TYPE_REGULAR, "b.bin", 16),
        ])
        self.add_inode(ROOT_INO, mode=IF_DIR | 0o755, links=3, dtime=0, mtime=DEL_SECRET,
                       size=BLOCK, blocks512=8, flags=FL_EXTENTS, gen=0x0002,
                       area=self.extent_area([(0, 1, ROOT_BLOCK, False)], 0x0002))
        self.add_inode(SUB_INO, mode=IF_DIR | 0o755, links=2, dtime=0, mtime=DEL_PHOTO,
                       size=BLOCK, blocks512=8, flags=FL_EXTENTS, gen=0x0012,
                       area=self.extent_area([(0, 1, SUB_BLOCK, False)], 0x0012))
        self.add_inode(MISC_INO, mode=IF_DIR | 0o755, links=2, dtime=0, mtime=DEL_PAIR,
                       size=BLOCK, blocks512=8, flags=FL_EXTENTS, gen=0x0013,
                       area=self.extent_area([(0, 1, MISC_BLOCK, False)], 0x0013))

    def write_live_files(self) -> None:
        self.add_inode(NOTES_INO, mode=IF_REG | 0o644, links=1, dtime=0, mtime=LIVE_MTIME,
                       size=1500, blocks512=16, flags=FL_EXTENTS, gen=0x1011,
                       area=self.extent_area([(0, 2, 20, False)], 0x1011))
        self.add_inode(KEEP_INO, mode=IF_REG | 0o644, links=1, dtime=0, mtime=LIVE_MTIME,
                       size=600, blocks512=8, flags=FL_EXTENTS, gen=0x1015,
                       area=self.extent_area([(0, 1, 26, False)], 0x1015))

    def write_deleted_files(self) -> None:
        deleted = [
            (SECRET_INO, 1500, [(0, 2, 22, False)], DEL_SECRET, 1700000400, 0x1014),
            (PHOTO_INO, 2500, [(0, 3, 30, False)], DEL_PHOTO, 1700000410, 0x1016),
            (ABIN_INO, 1024, [(0, 1, 40, False)], DEL_PAIR, 1700000420, 0x1017),
            (BBIN_INO, 1024, [(0, 1, 42, False)], DEL_PAIR, 1700000420, 0x1018),
        ]
        for ino, size, leaves, dtime, mtime, gen in deleted:
            self.add_inode(ino, mode=IF_REG | 0o644, links=0, dtime=dtime, mtime=mtime,
                           size=size, blocks512=(size + BLOCK - 1) // BLOCK * 8,
                           flags=FL_EXTENTS, gen=gen, area=self.extent_area(leaves, gen))

        # Deleted-shaped but re-allocated: the allocator owns this slot again, so the bytes
        # are somebody else's and the reader must not report the file at all.
        self.add_inode(REALLOC_INO, mode=IF_REG | 0o644, links=0, dtime=DEL_REALLOC,
                       mtime=1700000430, size=1024, blocks512=8, flags=FL_EXTENTS,
                       gen=0x1019, area=self.extent_area([(0, 1, 50, False)], 0x1019))
        self.mark_inode(REALLOC_INO)

        # Blocks claimed by a later write: recoverable in shape, wrong in substance.
        self.add_inode(REUSED_INO, mode=IF_REG | 0o644, links=0, dtime=DEL_REUSED,
                       mtime=1700000440, size=2048, blocks512=16, flags=FL_EXTENTS,
                       gen=0x1020, area=self.extent_area([(0, 2, 140, False)], 0x1020))

        inline = b"recover me if you can!!"
        self.add_inode(INLINE_INO, mode=IF_REG | 0o644, links=0, dtime=DEL_INLINE,
                       mtime=1700000450, size=len(inline), blocks512=8,
                       flags=FL_INLINE_DATA, gen=0x1021, area=self.inline_area(inline))

        # Two written blocks, an unallocated hole and an explicit punch hole: all three read
        # back as the zeros a hole is defined to hold.
        self.add_inode(SPARSE_INO, mode=IF_REG | 0o644, links=0, dtime=DEL_SPARSE,
                       mtime=1700000460, size=8 * BLOCK, blocks512=16, flags=FL_EXTENTS,
                       gen=0x1022,
                       area=self.extent_area([(0, 2, 150, False), (5, 2, 0, False)], 0x1022))

        # A pre-extents file: holes in the direct slots and one inside its index block.
        direct: list[int | None] = [160, None, 161, None, 162]
