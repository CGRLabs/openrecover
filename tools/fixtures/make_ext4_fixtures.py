DEL_SECRET = 1700000500  # root's i_mtime
DEL_PHOTO = 1700000550  # subdir's i_mtime
DEL_PAIR = 1700000600  # misc's i_mtime: two names, two inodes, same second
DEL_REALLOC = 1700000650
DEL_REUSED = 1700000700
DEL_INLINE = 1700000750
DEL_SPARSE = 1700000800
DEL_INDIRECT = 1700000850
DEL_BADCSUM = 1700000900
DEL_ENCRYPTED = 1700000950
DEL_UNWRITTEN = 1700001000
