#!/usr/bin/env python3
"""Build the deterministic exFAT disk-image fixtures for the M1 gate.

The committed gzip images are authoritative for CI; this builder exists so the
images can be regenerated byte-for-byte. Layout and entry encoding follow the
Microsoft exFAT specification so the images exercise the real parser (boot
validation, directory sets, set checksums, FAT chains, allocation bitmap).

Deleted entries are kept with their names intact but with the InUse bit cleared,
which is how exFAT marks a deletion. Two deleted files keep a surviving FAT chain
(contiguous and fragmented) while the rest rely on the NoFatChain flag or the
lost-chain contiguous fallback.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import struct
from datetime import datetime, timezone
from pathlib import Path

import file_builders as media

SECTOR = 512
TOTAL_SECTORS = 16384
BYTES_PER_CLUSTER = 2048
SECTORS_PER_CLUSTER = BYTES_PER_CLUSTER // SECTOR
FAT_OFFSET_SECTORS = 24
FAT_LENGTH_SECTORS = 32
HEAP_OFFSET_SECTORS = FAT_OFFSET_SECTORS + FAT_LENGTH_SECTORS
CLUSTER_COUNT = (TOTAL_SECTORS - HEAP_OFFSET_SECTORS) // SECTORS_PER_CLUSTER
VOLUME_BYTES = TOTAL_SECTORS * SECTOR
VOLUME_SERIAL = 0x4F524332
FAT_EOC = 0xFFFFFFFF

ROOT_CLUSTER = 2
BITMAP_CLUSTER = 3
UPCASE_CLUSTER = 4
DOCS_CLUSTER = 5
PICS_CLUSTER = 6
YEAR_CLUSTER = 7
OLD_STUFF_CLUSTER = 8

CRT = datetime(2023, 1, 2, 3, 4, 6, tzinfo=timezone.utc)
WRT = datetime(2024, 3, 5, 6, 7, 8, tzinfo=timezone.utc)
ACC = datetime(2024, 6, 7, 0, 0, 0, tzinfo=timezone.utc)

TIMESTAMP_NOTE = "exfat_local_time_assumed_utc"
LOST_CHAIN_NOTE = "fat_chain_lost; contiguous_assumption"


def put16(buf: bytearray, off: int, value: int) -> None:
    struct.pack_into("<H", buf, off, value)


def put32(buf: bytearray, off: int, value: int) -> None:
    struct.pack_into("<I", buf, off, value)


def put64(buf: bytearray, off: int, value: int) -> None:
    struct.pack_into("<Q", buf, off, value)


def exfat_timestamp(value: datetime) -> int:
    return (
        ((value.year - 1980) & 0x7F) << 25
        | (value.month & 0x0F) << 21
        | (value.day & 0x1F) << 16
        | (value.hour & 0x1F) << 11
        | (value.minute & 0x3F) << 5
        | ((value.second // 2) & 0x1F)
    )


def content_for(tag: str, size: int) -> bytes:
    stream = bytearray()
    counter = 0
    while len(stream) < size:
        stream += hashlib.sha256(f"{tag}:{counter}".encode("utf-8")).digest()
        counter += 1
    return bytes(stream[:size])


def unix_seconds(value: datetime) -> int:
    return int(value.timestamp())


def name_entries(name: str, in_use: bool) -> list[bytes]:
    encoded = name.encode("utf-16-le")
    units = list(struct.unpack("<%dH" % (len(encoded) // 2), encoded))
    assert len(units) <= 255
    out: list[bytes] = []
    entry_type = 0xC1 if in_use else 0x41
    for start in range(0, len(units), 15):
        chunk = units[start : start + 15]
        if len(chunk) < 15:
            chunk = chunk + [0x0000] + [0xFFFF] * (15 - len(chunk) - 1)
        raw = bytearray(32)
        raw[0] = entry_type
        for index, unit in enumerate(chunk):
            put16(raw, 2 + index * 2, unit)
        out.append(bytes(raw))
    return out


def entry_set(
    name: str,
    *,
    attributes: int,
    first_cluster: int,
    size: int,
    valid_size: int | None = None,
    no_fat_chain: bool,
    deleted: bool = False,
    timestamps: bool = True,
) -> bytes:
    """A primary + stream + name entries file/directory set with a valid checksum."""
    units = len(name.encode("utf-16-le")) // 2
    secondaries = 1 + len(name_entries(name, True)) if name else 1
    primary = bytearray(32)
    primary[0] = 0x85
    primary[1] = secondaries
    put16(primary, 4, attributes)
    if timestamps:
        put32(primary, 8, exfat_timestamp(CRT))
        put32(primary, 12, exfat_timestamp(WRT))
        put32(primary, 16, exfat_timestamp(ACC))
        primary[20] = 0
        primary[21] = 0
        primary[22] = 0x80
        primary[23] = 0x80
        primary[24] = 0x80

    stream = bytearray(32)
    stream[0] = 0xC0
    stream[1] = 0x01 | (0x02 if no_fat_chain else 0x00)
    stream[3] = units
    put16(stream, 4, name_hash(name))
    put64(stream, 8, valid_size if valid_size is not None else size)
    put32(stream, 20, first_cluster)
    put64(stream, 24, size)

    entries = bytes(primary) + bytes(stream)
    names = b"".join(name_entries(name, True))
    entries += names

    checksum = set_checksum(entries)
    put16(primary, 2, checksum)
    entries = bytes(primary) + bytes(stream) + names

    if deleted:
        raw = bytearray(entries)
        for offset in range(0, len(raw), 32):
            raw[offset] &= 0x7F
        entries = bytes(raw)
    return entries


def name_hash(name: str) -> int:
    total = 0
    for unit in struct.unpack("<%dH" % (len(name.encode("utf-16-le")) // 2), name.encode("utf-16-le")):
        total = (((total & 1) << 15) + (total >> 1) + unit) & 0xFFFF
    return total


def set_checksum(entries: bytes) -> int:
    total = 0
    for index, byte in enumerate(entries):
        if index in (2, 3):
            continue
        total = (((total & 1) << 15) + (total >> 1) + byte) & 0xFFFF
    return total


def metadata_entry(entry_type: int, first_cluster: int, size: int) -> bytes:
    raw = bytearray(32)
    raw[0] = entry_type
    put32(raw, 20, first_cluster)
    put64(raw, 24, size)
    return bytes(raw)


def label_entry(label: str) -> bytes:
    raw = bytearray(32)
    raw[0] = 0x83
    raw[1] = len(label)
    encoded = label.encode("utf-16-le")
    raw[2 : 2 + len(encoded)] = encoded
    return bytes(raw)


def upcase_table() -> bytes:
    return b"".join(struct.pack("<H", value) for value in range(256))


class ExfatVolume:
    def __init__(self) -> None:
        self.img = bytearray(VOLUME_BYTES)
        self.fat = [0] * (FAT_LENGTH_SECTORS * SECTOR // 4)
        self.allocated: set[int] = set()
        self.fat[0] = 0xFFFFFFF8
        self.fat[1] = 0xFFFFFFFF

    def cluster_offset(self, cluster: int) -> int:
        assert 2 <= cluster < CLUSTER_COUNT + 2, cluster
        return (HEAP_OFFSET_SECTORS + (cluster - 2) * SECTORS_PER_CLUSTER) * SECTOR

    def write_cluster(self, cluster: int, data: bytes) -> None:
        assert len(data) <= BYTES_PER_CLUSTER
        offset = self.cluster_offset(cluster)
        self.img[offset : offset + len(data)] = data

    def chain(self, first: int, count: int, *, end_of_chain: bool = True) -> None:
        for index in range(count):
            self.fat[first + index] = (
                first + index + 1 if index + 1 < count else (FAT_EOC if end_of_chain else 0)
            )

    def write_file(self, first: int, data: bytes, *, allocated: bool, chain: bool = True) -> None:
        if not data:
            return
        count = (len(data) + BYTES_PER_CLUSTER - 1) // BYTES_PER_CLUSTER
        if chain:
            self.chain(first, count)
        if allocated:
            self.allocated.update(range(first, first + count))
        for index in range(count):
            chunk = data[index * BYTES_PER_CLUSTER : (index + 1) * BYTES_PER_CLUSTER]
            self.write_cluster(first + index, chunk)

    def mark_allocated(self, *clusters: int) -> None:
        self.allocated.update(clusters)

    def write_directory(self, cluster: int, entries: list[bytes]) -> None:
        raw = b"".join(entries)
        assert len(raw) <= BYTES_PER_CLUSTER, (len(raw), BYTES_PER_CLUSTER)
        self.write_cluster(cluster, raw + b"\x00" * (BYTES_PER_CLUSTER - len(raw)))

    def finalize_boot(self) -> None:
        boot = bytearray(SECTOR)
        boot[0:3] = b"\xEB\x76\x90"
        boot[3:11] = b"EXFAT   "
        put64(boot, 0x40, 0)
        put64(boot, 0x48, TOTAL_SECTORS)
        put32(boot, 0x50, FAT_OFFSET_SECTORS)
        put32(boot, 0x54, FAT_LENGTH_SECTORS)
        put32(boot, 0x58, HEAP_OFFSET_SECTORS)
        put32(boot, 0x5C, CLUSTER_COUNT)
        put32(boot, 0x60, ROOT_CLUSTER)
        put32(boot, 0x64, VOLUME_SERIAL)
        put16(boot, 0x68, 0x0100)
        put16(boot, 0x6A, 0)
        boot[0x6C] = 9
        boot[0x6D] = 2
        boot[0x6E] = 1
        boot[0x6F] = 0x80
        percent = min(100, (len(self.allocated) * 100 + CLUSTER_COUNT - 1) // CLUSTER_COUNT)
        boot[0x70] = percent
        boot[510] = 0x55
        boot[511] = 0xAA
        self.img[0:SECTOR] = boot
        self.img[12 * SECTOR : 13 * SECTOR] = boot

        fat_bytes = bytearray(FAT_LENGTH_SECTORS * SECTOR)
        for index, value in enumerate(self.fat):
            put32(fat_bytes, index * 4, value)
        start = FAT_OFFSET_SECTORS * SECTOR
        self.img[start : start + len(fat_bytes)] = fat_bytes

    def write_bitmap(self) -> None:
        self.allocated.add(BITMAP_CLUSTER)
        self.fat[BITMAP_CLUSTER] = FAT_EOC
        bitmap = bytearray((CLUSTER_COUNT + 7) // 8)
        for cluster in self.allocated:
            index = cluster - 2
            bitmap[index // 8] |= 1 << (index % 8)
        self.write_cluster(BITMAP_CLUSTER, bytes(bitmap))


def recovered_entry(
    path: str,
    size: int,
    *,
    extents: list[tuple[int, int]],
    low: bool = False,
    flags: list[str] | None = None,
    notes: list[str] | None = None,
) -> dict:
    all_flags = list(flags or [])
    if low:
        all_flags.append("ClustersReallocated")
    all_flags.sort()
    all_notes = [TIMESTAMP_NOTE]
    all_notes.extend(notes or [])
    trimmed: list[tuple[int, int]] = []
    remaining = size
    for offset, length in extents:
        if remaining == 0:
            break
        take = min(length, remaining)
        trimmed.append((offset, take))
        remaining -= take
    return {
        "path": path,
        "name": path.rsplit("/", 1)[-1],
        "size_bytes": size,
        "extents": [
            {"offset_bytes": offset, "length_bytes": length, "sparse": False}
            for offset, length in trimmed
        ],
        "confidence": "low" if low else "high",
        "flags": all_flags,
        "note": "; ".join(all_notes),
        "mtime_unix": unix_seconds(WRT),
        "ctime_unix": unix_seconds(CRT),
        "atime_unix": unix_seconds(ACC),
        "origin": "filesystem_metadata",
    }


def cluster_offset(cluster: int) -> int:
    return (HEAP_OFFSET_SECTORS + (cluster - 2) * SECTORS_PER_CLUSTER) * SECTOR


def build_basic() -> tuple[bytes, list[dict], dict[str, str]]:
    deleted_photo = media.build_jpeg(entropy_size=300)
    volume = ExfatVolume()
    root: list[bytes] = [
        label_entry("OPENRCVR"),
        metadata_entry(0x81, BITMAP_CLUSTER, (CLUSTER_COUNT + 7) // 8),
        metadata_entry(0x82, UPCASE_CLUSTER, 512),
    ]
    docs: list[bytes] = []
    pics: list[bytes] = []
    year2024: list[bytes] = []
    old_stuff: list[bytes] = []
    content: dict[str, bytes] = {}

    def add(
        directory: list[bytes],
        name: str,
        cluster: int,
        data: bytes,
        *,
        attributes: int = 0x20,
        deleted: bool = False,
        no_fat_chain: bool = True,
        chain: bool = True,
        keep_fat_chain: bool = False,
    ) -> None:
        if data:
            volume.write_file(cluster, data, allocated=not deleted, chain=chain)
            if keep_fat_chain and deleted:
                # Deletion clears the bitmap but can leave the FAT chain behind.
                count = (len(data) + BYTES_PER_CLUSTER - 1) // BYTES_PER_CLUSTER
                volume.chain(cluster, count)
        directory.append(
            entry_set(
                name,
                attributes=attributes,
                first_cluster=cluster,
                size=len(data) if attributes & 0x10 == 0 else BYTES_PER_CLUSTER,
                no_fat_chain=no_fat_chain,
                deleted=deleted,
            )
        )
        if attributes & 0x10 == 0:
            content[name] = data

    # Live files and directories.
    add(root, "README.TXT", 10, content_for("readme.txt", 40))
    add(root, "DOCS", DOCS_CLUSTER, b"", attributes=0x10, chain=False)
    add(root, "PICS", PICS_CLUSTER, b"", attributes=0x10, chain=False)

    # Deleted root-level files.
    add(root, "plain.txt", 14, content_for("plain.txt", 3000), deleted=True)
    add(root, "notes.txt", 16, content_for("notes.txt", 10), deleted=True)
    add(root, "empty.txt", 0, b"", deleted=True)
    fragmented = content_for("fragmented.bin", 3000)
    volume.write_cluster(22, fragmented[:BYTES_PER_CLUSTER])
    volume.write_cluster(30, fragmented[BYTES_PER_CLUSTER:])
    volume.fat[22] = 30
    volume.fat[30] = FAT_EOC
    root.append(
        entry_set("fragmented.bin", attributes=0x20, first_cluster=22, size=len(fragmented),
                  no_fat_chain=False, deleted=True)
    )
    content["fragmented.bin"] = fragmented

    # Deleted directory; its FAT chain is gone and its clusters are free, so the
    # scanner must use the intact-entry heuristic and read it contiguously.
    add(root, "Old Stuff", OLD_STUFF_CLUSTER, b"", attributes=0x10, deleted=True,
        no_fat_chain=False, chain=False)
    add(old_stuff, "inner one.bin", 26, content_for("inner one.bin", 2048), deleted=True)
    add(old_stuff, "inner two.bin", 27, content_for("inner two.bin", 700), deleted=True)

    add(docs, "Quarterly results.txt", 11, content_for("Quarterly results.txt", 1800))
    # A deleted file whose FAT chain survived.
    add(docs, "Quarterly report 2024.txt", 17, content_for("Quarterly report 2024.txt", 5000),
        deleted=True, no_fat_chain=False, chain=False, keep_fat_chain=True)
    # A deleted file whose FAT chain was cleared: contiguous fallback.
    add(docs, "Ünïcødé résumé.pdf", 20, content_for("Unicode resume", 1200), deleted=True,
        no_fat_chain=False, chain=False)

    add(pics, "2024", YEAR_CLUSTER, b"", attributes=0x10, chain=False)
    add(year2024, "Ω-ảnh đẹp.jpg", 12, content_for("Omega photo", 2500))
    add(year2024, "summer holiday photo.jpg", 21, deleted_photo, deleted=True)
    add(year2024, "data.csv", 25, content_for("data.csv", 100), deleted=True)

    volume.write_directory(ROOT_CLUSTER, root)
    volume.write_directory(DOCS_CLUSTER, docs)
    volume.write_directory(PICS_CLUSTER, pics)
    volume.write_directory(YEAR_CLUSTER, year2024)
    volume.write_directory(OLD_STUFF_CLUSTER, old_stuff)
    volume.fat[ROOT_CLUSTER] = FAT_EOC
    volume.fat[DOCS_CLUSTER] = FAT_EOC
    volume.fat[PICS_CLUSTER] = FAT_EOC
    volume.fat[YEAR_CLUSTER] = FAT_EOC
    volume.mark_allocated(
        ROOT_CLUSTER, DOCS_CLUSTER, PICS_CLUSTER, YEAR_CLUSTER, 10, 11, 12, UPCASE_CLUSTER
    )
    volume.fat[UPCASE_CLUSTER] = FAT_EOC
    volume.write_cluster(UPCASE_CLUSTER, upcase_table())
    volume.write_bitmap()
    volume.finalize_boot()

    cluster = cluster_offset
    files = [
        recovered_entry("plain.txt", 3000, extents=[(cluster(14), 3000)]),
        recovered_entry("notes.txt", 10, extents=[(cluster(16), 10)]),
        recovered_entry("empty.txt", 0, extents=[]),
        recovered_entry("fragmented.bin", 3000,
                        extents=[(cluster(22), BYTES_PER_CLUSTER), (cluster(30), 952)]),
        recovered_entry("DOCS/Quarterly report 2024.txt", 5000,
                        extents=[(cluster(17), 3 * BYTES_PER_CLUSTER)]),
        recovered_entry("DOCS/Ünïcødé résumé.pdf", 1200, extents=[(cluster(20), 1200)],
                        notes=[LOST_CHAIN_NOTE]),
        recovered_entry("PICS/2024/summer holiday photo.jpg", len(deleted_photo),
                        extents=[(cluster(21), len(deleted_photo))]),
        recovered_entry("PICS/2024/data.csv", 100, extents=[(cluster(25), 100)]),
        recovered_entry("Old Stuff/inner one.bin", 2048,
                        extents=[(cluster(26), BYTES_PER_CLUSTER)]),
        recovered_entry("Old Stuff/inner two.bin", 700, extents=[(cluster(27), 700)]),
    ]

    hashes = {
        entry["path"]: hashlib.sha256(content[entry["name"]]).hexdigest() for entry in files
    }
    return bytes(volume.img), files, hashes


def build_reused() -> tuple[bytes, list[dict], dict[str, str]]:
    volume = ExfatVolume()
    root: list[bytes] = [
        label_entry("OPENRCVR"),
        metadata_entry(0x81, BITMAP_CLUSTER, (CLUSTER_COUNT + 7) // 8),
        metadata_entry(0x82, UPCASE_CLUSTER, 512),
    ]

    live = content_for("new data.bin", 4096)
    root.append(
        entry_set("new data.bin", attributes=0x20, first_cluster=7, size=len(live),
                  no_fat_chain=True)
    )
    volume.write_file(7, live, allocated=True)
    volume.mark_allocated(7, 8)

    root.append(
        entry_set("Reused report.docx", attributes=0x20, first_cluster=7, size=4096,
                  no_fat_chain=True, deleted=True)
    )
    keep = content_for("keep.txt", 100)
    root.append(
        entry_set("keep.txt", attributes=0x20, first_cluster=9, size=len(keep),
                  no_fat_chain=True, deleted=True)
    )
    volume.write_file(9, keep, allocated=False)

    volume.write_directory(ROOT_CLUSTER, root)
    volume.fat[ROOT_CLUSTER] = FAT_EOC
    volume.mark_allocated(ROOT_CLUSTER, UPCASE_CLUSTER)
    volume.write_cluster(UPCASE_CLUSTER, upcase_table())
    volume.write_bitmap()
    volume.finalize_boot()

    cluster = cluster_offset
    files = [
        recovered_entry("Reused report.docx", 4096,
                        extents=[(cluster(7), 4096)], low=True),
        recovered_entry("keep.txt", 100, extents=[(cluster(9), 100)]),
    ]
    hashes = {"keep.txt": hashlib.sha256(keep).hexdigest()}
    return bytes(volume.img), files, hashes


def write_gzip(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9) as gz:
            gz.write(data)


def write_json(path: Path, document: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False)
    path.write_text(text + "\n", encoding="utf-8")


def golden_document(image_name: str, image: bytes, files: list[dict], hashes: dict[str, str]) -> dict:
    return {
        "image": image_name,
        "image_sha256": hashlib.sha256(image).hexdigest(),
        "volume_bytes": VOLUME_BYTES,
        "files": sorted(files, key=lambda entry: entry["path"]),
        "hashes": dict(sorted(hashes.items())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    repo = Path(__file__).resolve().parents[2]
    parser.add_argument("--images", type=Path, default=repo / "tests/fixtures/images")
    parser.add_argument("--golden", type=Path, default=repo / "tests/fixtures/golden")
    args = parser.parse_args()

    basic, basic_files, basic_hashes = build_basic()
    reused, reused_files, reused_hashes = build_reused()

    documents = {
        "exfat_basic": golden_document("exfat_basic.img", basic, basic_files, basic_hashes),
        "exfat_reused": golden_document("exfat_reused.img", reused, reused_files, reused_hashes),
    }
    images = {
        "exfat_basic.img": basic,
        "exfat_reused.img": reused,
    }

    for name, image in images.items():
        write_gzip(args.images / (name + ".gz"), image)
    for name, document in documents.items():
        write_json(args.golden / (name + ".golden.json"), document)

    print(f"wrote {len(images)} images to {args.images}")
    print(f"wrote {len(documents)} goldens to {args.golden}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
